CREATE TABLE event_registrations
(
    event_registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id               BIGINT      NOT NULL,
    event_id              BIGINT      NOT NULL,
    status                VARCHAR(20) NOT NULL,
    registered_at         TIMESTAMPTZ NOT NULL,
    activated_at          TIMESTAMPTZ NOT NULL,
    left_at               TIMESTAMPTZ,
    updated_at            TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_event_registrations PRIMARY KEY (event_registration_id),
    CONSTRAINT fk_event_registrations_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_event_registrations_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_event_registrations_user_event UNIQUE (user_id, event_id),
    CONSTRAINT ck_event_registrations_status
        CHECK (status IN ('ACTIVE', 'LEFT')),
    CONSTRAINT ck_event_registrations_state
        CHECK (
            (status = 'ACTIVE' AND left_at IS NULL)
            OR (status = 'LEFT' AND left_at IS NOT NULL)
        ),
    CONSTRAINT ck_event_registrations_timestamps
        CHECK (
            registered_at <= activated_at
            AND activated_at <= updated_at
            AND (
                left_at IS NULL
                OR (activated_at <= left_at AND left_at <= updated_at)
            )
        )
);

CREATE INDEX idx_event_registrations_user_status_event
    ON event_registrations (user_id, status, event_id);

CREATE INDEX idx_event_registrations_event_status
    ON event_registrations (event_id, status, event_registration_id);


CREATE TABLE activity_registrations
(
    activity_registration_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_registration_id    BIGINT      NOT NULL,
    activity_id              BIGINT      NOT NULL,
    status                   VARCHAR(20) NOT NULL,
    cancellation_source      VARCHAR(20),
    registered_at            TIMESTAMPTZ NOT NULL,
    activated_at             TIMESTAMPTZ NOT NULL,
    cancelled_at             TIMESTAMPTZ,
    no_show_at               TIMESTAMPTZ,
    updated_at               TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_activity_registrations PRIMARY KEY (activity_registration_id),
    CONSTRAINT fk_activity_registrations_event_registration
        FOREIGN KEY (event_registration_id)
        REFERENCES event_registrations (event_registration_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_registrations_activity
        FOREIGN KEY (activity_id)
        REFERENCES activities (activity_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_activity_registrations_event_registration_activity
        UNIQUE (event_registration_id, activity_id),
    CONSTRAINT ck_activity_registrations_status
        CHECK (status IN ('ACTIVE', 'CANCELLED', 'NO_SHOW')),
    CONSTRAINT ck_activity_registrations_cancellation_source
        CHECK (
            cancellation_source IS NULL
            OR cancellation_source IN ('PARTICIPANT', 'ACTIVITY', 'EVENT')
        ),
    CONSTRAINT ck_activity_registrations_state
        CHECK (
            (
                status = 'ACTIVE'
                AND cancellation_source IS NULL
                AND cancelled_at IS NULL
                AND no_show_at IS NULL
            )
            OR (
                status = 'CANCELLED'
                AND cancellation_source IS NOT NULL
                AND cancelled_at IS NOT NULL
                AND no_show_at IS NULL
            )
            OR (
                status = 'NO_SHOW'
                AND cancellation_source IS NULL
                AND cancelled_at IS NULL
                AND no_show_at IS NOT NULL
            )
        ),
    CONSTRAINT ck_activity_registrations_timestamps
        CHECK (
            registered_at <= activated_at
            AND activated_at <= updated_at
            AND (
                cancelled_at IS NULL
                OR (activated_at <= cancelled_at AND cancelled_at <= updated_at)
            )
            AND (
                no_show_at IS NULL
                OR (activated_at <= no_show_at AND no_show_at <= updated_at)
            )
        )
);

CREATE INDEX idx_activity_registrations_event_registration_status
    ON activity_registrations (event_registration_id, status, activity_registration_id);

CREATE INDEX idx_activity_registrations_activity_status
    ON activity_registrations (activity_id, status, activity_registration_id);

CREATE INDEX idx_activity_registrations_active_capacity
    ON activity_registrations (activity_id, activity_registration_id)
    WHERE status = 'ACTIVE';


CREATE TABLE attendances
(
    attendance_id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_registration_id BIGINT      NOT NULL,
    status                   VARCHAR(20) NOT NULL,
    recorded_source          VARCHAR(30) NOT NULL,
    attended_at              TIMESTAMPTZ NOT NULL,
    created_at               TIMESTAMPTZ NOT NULL,
    updated_at               TIMESTAMPTZ NOT NULL,
    voided_at                TIMESTAMPTZ,

    CONSTRAINT pk_attendances PRIMARY KEY (attendance_id),
    CONSTRAINT fk_attendances_activity_registration
        FOREIGN KEY (activity_registration_id)
        REFERENCES activity_registrations (activity_registration_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_attendances_activity_registration UNIQUE (activity_registration_id),
    CONSTRAINT ck_attendances_status
        CHECK (status IN ('VALID', 'VOIDED')),
    CONSTRAINT ck_attendances_recorded_source
        CHECK (recorded_source IN ('SELF_SCAN', 'ORGANIZER_CORRECTION')),
    CONSTRAINT ck_attendances_state
        CHECK (
            (status = 'VALID' AND voided_at IS NULL)
            OR (status = 'VOIDED' AND voided_at IS NOT NULL)
        ),
    CONSTRAINT ck_attendances_timestamps
        CHECK (
            created_at <= updated_at
            AND (voided_at IS NULL OR voided_at <= updated_at)
        )
);

CREATE INDEX idx_attendances_status_attended
    ON attendances (status, attended_at, attendance_id);


CREATE TABLE attendance_adjustments
(
    attendance_adjustment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_registration_id BIGINT       NOT NULL,
    actor_user_id            BIGINT       NOT NULL,
    idempotency_key          UUID         NOT NULL,
    previous_state           JSONB        NOT NULL,
    new_state                JSONB        NOT NULL,
    effective_attended_at    TIMESTAMPTZ,
    reason                   VARCHAR(500) NOT NULL,
    adjusted_at              TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_attendance_adjustments PRIMARY KEY (attendance_adjustment_id),
    CONSTRAINT fk_attendance_adjustments_activity_registration
        FOREIGN KEY (activity_registration_id)
        REFERENCES activity_registrations (activity_registration_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_attendance_adjustments_actor_user
        FOREIGN KEY (actor_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_attendance_adjustments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_attendance_adjustments_previous_state_object
        CHECK (jsonb_typeof(previous_state) = 'object'),
    CONSTRAINT ck_attendance_adjustments_new_state_object
        CHECK (jsonb_typeof(new_state) = 'object'),
    CONSTRAINT ck_attendance_adjustments_previous_state_shape
        CHECK (
            previous_state ?& ARRAY[
                'registration_status',
                'cancellation_source',
                'attendance_status',
                'attended_at',
                'derived_display_outcome'
            ]
        ),
    CONSTRAINT ck_attendance_adjustments_new_state_shape
        CHECK (
            new_state ?& ARRAY[
                'registration_status',
                'cancellation_source',
                'attendance_status',
                'attended_at',
                'derived_display_outcome'
            ]
        ),
    CONSTRAINT ck_attendance_adjustments_state_changed
        CHECK (previous_state <> new_state),
    CONSTRAINT ck_attendance_adjustments_reason
        CHECK (
            reason = BTRIM(reason)
            AND CHAR_LENGTH(reason) BETWEEN 10 AND 500
        ),
    CONSTRAINT ck_attendance_adjustments_effective_attendance
        CHECK (
            (
                new_state ->> 'attendance_status' = 'VALID'
                AND effective_attended_at IS NOT NULL
                AND new_state ->> 'attended_at' IS NOT NULL
                AND (new_state ->> 'attended_at')::TIMESTAMPTZ = effective_attended_at
            )
            OR (
                new_state ->> 'attendance_status' IS DISTINCT FROM 'VALID'
                AND effective_attended_at IS NULL
            )
        )
);

CREATE INDEX idx_attendance_adjustments_registration_adjusted
    ON attendance_adjustments (
        activity_registration_id,
        adjusted_at,
        attendance_adjustment_id
    );

CREATE INDEX idx_attendance_adjustments_actor_user
    ON attendance_adjustments (actor_user_id, adjusted_at DESC);


CREATE TABLE certificates
(
    certificate_id         BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attendance_id          BIGINT       NOT NULL,
    certificate_code       VARCHAR(50)  NOT NULL,
    recipient_name_snapshot VARCHAR(100) NOT NULL,
    file_url               TEXT,
    status                 VARCHAR(20)  NOT NULL,
    issued_at              TIMESTAMPTZ  NOT NULL,
    revoked_at             TIMESTAMPTZ,
    created_at             TIMESTAMPTZ  NOT NULL,
    updated_at             TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_certificates PRIMARY KEY (certificate_id),
    CONSTRAINT fk_certificates_attendance
        FOREIGN KEY (attendance_id)
        REFERENCES attendances (attendance_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_certificates_attendance UNIQUE (attendance_id),
    CONSTRAINT uk_certificates_code UNIQUE (certificate_code),
    CONSTRAINT ck_certificates_code_not_blank
        CHECK (BTRIM(certificate_code) <> ''),
    CONSTRAINT ck_certificates_recipient_name
        CHECK (
            recipient_name_snapshot = BTRIM(recipient_name_snapshot)
            AND BTRIM(recipient_name_snapshot) <> ''
        ),
    CONSTRAINT ck_certificates_status
        CHECK (status IN ('ISSUED', 'REVOKED')),
    CONSTRAINT ck_certificates_state
        CHECK (
            (status = 'ISSUED' AND revoked_at IS NULL)
            OR (status = 'REVOKED' AND revoked_at IS NOT NULL)
        ),
    CONSTRAINT ck_certificates_timestamps
        CHECK (
            created_at <= issued_at
            AND issued_at <= updated_at
            AND (revoked_at IS NULL OR revoked_at <= updated_at)
        )
);


CREATE TABLE activity_ratings
(
    activity_rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    attendance_id      BIGINT        NOT NULL,
    rating_score       SMALLINT      NOT NULL,
    comment            VARCHAR(1000),
    status             VARCHAR(20)   NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL,
    updated_at         TIMESTAMPTZ   NOT NULL,
    invalidated_at     TIMESTAMPTZ,

    CONSTRAINT pk_activity_ratings PRIMARY KEY (activity_rating_id),
    CONSTRAINT fk_activity_ratings_attendance
        FOREIGN KEY (attendance_id)
        REFERENCES attendances (attendance_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_activity_ratings_attendance UNIQUE (attendance_id),
    CONSTRAINT ck_activity_ratings_score
        CHECK (rating_score BETWEEN 1 AND 5),
    CONSTRAINT ck_activity_ratings_comment
        CHECK (
            comment IS NULL
            OR (
                comment = BTRIM(comment)
                AND CHAR_LENGTH(comment) BETWEEN 1 AND 1000
            )
        ),
    CONSTRAINT ck_activity_ratings_status
        CHECK (status IN ('ACTIVE', 'INVALIDATED')),
    CONSTRAINT ck_activity_ratings_state
        CHECK (
            (status = 'ACTIVE' AND invalidated_at IS NULL)
            OR (status = 'INVALIDATED' AND invalidated_at IS NOT NULL)
        ),
    CONSTRAINT ck_activity_ratings_timestamps
        CHECK (
            created_at <= updated_at
            AND (invalidated_at IS NULL OR invalidated_at <= updated_at)
        )
);


CREATE TABLE notifications
(
    notification_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    recipient_user_id BIGINT       NOT NULL,
    notification_type VARCHAR(60)  NOT NULL,
    event_id           BIGINT,
    activity_id        BIGINT,
    certificate_id     BIGINT,
    deduplication_key  VARCHAR(200) NOT NULL,
    title              VARCHAR(200) NOT NULL,
    message            TEXT         NOT NULL,
    created_at         TIMESTAMPTZ  NOT NULL,
    read_at            TIMESTAMPTZ,

    CONSTRAINT pk_notifications PRIMARY KEY (notification_id),
    CONSTRAINT fk_notifications_recipient_user
        FOREIGN KEY (recipient_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_activity
        FOREIGN KEY (activity_id)
        REFERENCES activities (activity_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_notifications_certificate
        FOREIGN KEY (certificate_id)
        REFERENCES certificates (certificate_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_notifications_recipient_deduplication
        UNIQUE (recipient_user_id, deduplication_key),
    CONSTRAINT ck_notifications_type
        CHECK (notification_type IN (
            'ACTIVITY_SCHEDULE_OR_LOCATION_CHANGED',
            'ACTIVITY_CANCELLED',
            'EVENT_CANCELLED',
            'CERTIFICATE_ISSUED',
            'CERTIFICATE_REVOKED'
        )),
    CONSTRAINT ck_notifications_reference
        CHECK (
            (
                notification_type IN (
                    'ACTIVITY_SCHEDULE_OR_LOCATION_CHANGED',
                    'ACTIVITY_CANCELLED'
                )
                AND activity_id IS NOT NULL
                AND event_id IS NULL
                AND certificate_id IS NULL
            )
            OR (
                notification_type = 'EVENT_CANCELLED'
                AND event_id IS NOT NULL
                AND activity_id IS NULL
                AND certificate_id IS NULL
            )
            OR (
                notification_type IN ('CERTIFICATE_ISSUED', 'CERTIFICATE_REVOKED')
                AND certificate_id IS NOT NULL
                AND event_id IS NULL
                AND activity_id IS NULL
            )
        ),
    CONSTRAINT ck_notifications_deduplication_key
        CHECK (
            deduplication_key = BTRIM(deduplication_key)
            AND BTRIM(deduplication_key) <> ''
        ),
    CONSTRAINT ck_notifications_title
        CHECK (title = BTRIM(title) AND BTRIM(title) <> ''),
    CONSTRAINT ck_notifications_message
        CHECK (message = BTRIM(message) AND BTRIM(message) <> ''),
    CONSTRAINT ck_notifications_read_time
        CHECK (read_at IS NULL OR read_at >= created_at)
);

CREATE INDEX idx_notifications_recipient_created
    ON notifications (recipient_user_id, created_at DESC, notification_id DESC);

CREATE INDEX idx_notifications_recipient_unread
    ON notifications (recipient_user_id, notification_id)
    WHERE read_at IS NULL;
