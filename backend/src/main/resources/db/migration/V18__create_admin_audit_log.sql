ALTER TABLE users
    ADD COLUMN sessions_valid_from TIMESTAMPTZ;

CREATE TABLE admin_audit_logs
(
    audit_log_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    actor_user_id BIGINT       NOT NULL,
    action        VARCHAR(40)  NOT NULL,
    target_type   VARCHAR(30)  NOT NULL,
    target_id     BIGINT       NOT NULL,
    target_label  VARCHAR(200) NOT NULL,
    reason        VARCHAR(500),
    details       JSONB        NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_admin_audit_logs PRIMARY KEY (audit_log_id),
    CONSTRAINT fk_admin_audit_logs_actor
        FOREIGN KEY (actor_user_id) REFERENCES users (user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_admin_audit_logs_target_positive
        CHECK (target_id > 0),
    CONSTRAINT ck_admin_audit_logs_target_label
        CHECK (BTRIM(target_label) <> ''),
    CONSTRAINT ck_admin_audit_logs_details_object
        CHECK (jsonb_typeof(details) = 'object'),
    CONSTRAINT ck_admin_audit_logs_action_target
        CHECK (
            (target_type = 'USER' AND action IN (
                'USER_CREATED', 'USER_UPDATED', 'USER_LOCKED', 'USER_UNLOCKED',
                'ROLE_ASSIGNED', 'ROLE_REMOVED'))
            OR (target_type = 'PARTNER_ORGANIZATION' AND action IN (
                'ORGANIZATION_LOCKED', 'ORGANIZATION_UNLOCKED'))
            OR (target_type = 'BADGE' AND action IN (
                'BADGE_CREATED', 'BADGE_UPDATED', 'BADGE_AWARDS_SYNCHRONIZED'))
        ),
    CONSTRAINT ck_admin_audit_logs_reason
        CHECK (
            (action IN ('USER_LOCKED', 'USER_UNLOCKED',
                        'ORGANIZATION_LOCKED', 'ORGANIZATION_UNLOCKED')
                AND reason IS NOT NULL
                AND CHAR_LENGTH(BTRIM(reason)) BETWEEN 10 AND 500)
            OR (action NOT IN ('USER_LOCKED', 'USER_UNLOCKED',
                               'ORGANIZATION_LOCKED', 'ORGANIZATION_UNLOCKED')
                AND reason IS NULL)
        )
);

CREATE INDEX idx_admin_audit_logs_created
    ON admin_audit_logs (created_at DESC, audit_log_id DESC);

CREATE INDEX idx_admin_audit_logs_actor_created
    ON admin_audit_logs (actor_user_id, created_at DESC, audit_log_id DESC);

CREATE INDEX idx_admin_audit_logs_target_created
    ON admin_audit_logs (target_type, target_id, created_at DESC, audit_log_id DESC);

CREATE INDEX idx_admin_audit_logs_action_created
    ON admin_audit_logs (action, created_at DESC, audit_log_id DESC);
