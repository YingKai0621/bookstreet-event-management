CREATE TABLE users
(
    user_id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    username          VARCHAR(30)  NOT NULL,
    email             VARCHAR(255),
    password_hash     VARCHAR(255) NOT NULL,
    full_name         VARCHAR(100) NOT NULL,
    phone_number      VARCHAR(20),
    avatar_url        TEXT,
    email_verified_at TIMESTAMPTZ,
    status            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (user_id),
    CONSTRAINT ck_users_status
        CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX uk_users_username_ci
    ON users (LOWER(username));

CREATE UNIQUE INDEX uk_users_email_ci
    ON users (LOWER(email))
    WHERE email IS NOT NULL;


CREATE TABLE roles
(
    role_id     SMALLINT GENERATED BY DEFAULT AS IDENTITY,
    code        VARCHAR(30)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description TEXT,

    CONSTRAINT pk_roles PRIMARY KEY (role_id),
    CONSTRAINT uk_roles_code UNIQUE (code),
    CONSTRAINT ck_roles_code
        CHECK (code IN (
            'PARTICIPANT',
            'PARTNER',
            'ORGANIZER',
            'ADMIN'
        ))
);


CREATE TABLE user_roles
(
    user_role_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT      NOT NULL,
    role_id      SMALLINT    NOT NULL,
    assigned_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_roles PRIMARY KEY (user_role_id),

    CONSTRAINT fk_user_roles_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_user_roles_role
        FOREIGN KEY (role_id)
        REFERENCES roles (role_id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_user_roles_user_role
        UNIQUE (user_id, role_id)
);


CREATE TABLE user_tokens
(
    token_id    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    token_type  VARCHAR(30)  NOT NULL,
    token_hash  VARCHAR(255) NOT NULL,
    expires_at  TIMESTAMPTZ  NOT NULL,
    used_at     TIMESTAMPTZ,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_user_tokens PRIMARY KEY (token_id),
    CONSTRAINT uk_user_tokens_token_hash UNIQUE (token_hash),

    CONSTRAINT fk_user_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_user_tokens_type
        CHECK (token_type IN (
            'EMAIL_VERIFICATION',
            'PASSWORD_RESET'
        ))
);

CREATE INDEX idx_user_roles_user_id
    ON user_roles (user_id);

CREATE INDEX idx_user_roles_role_id
    ON user_roles (role_id);

CREATE INDEX idx_user_tokens_user_id
    ON user_tokens (user_id);

CREATE INDEX idx_user_tokens_expires_at
    ON user_tokens (expires_at);