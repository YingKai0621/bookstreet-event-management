CREATE TABLE locations
(
    location_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code         VARCHAR(30)  NOT NULL,
    name         VARCHAR(100) NOT NULL,
    location_type VARCHAR(30) NOT NULL,
    description  TEXT,
    max_capacity INTEGER      NOT NULL,
    map_x        NUMERIC(10, 2),
    map_y        NUMERIC(10, 2),
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_locations PRIMARY KEY (location_id),
    CONSTRAINT uk_locations_code UNIQUE (code),
    CONSTRAINT ck_locations_code_not_blank
        CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_locations_name_not_blank
        CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_locations_type_not_blank
        CHECK (BTRIM(location_type) <> ''),
    CONSTRAINT ck_locations_max_capacity_positive
        CHECK (max_capacity > 0)
);


CREATE TABLE booths
(
    booth_id      BIGINT      NOT NULL,
    category_code VARCHAR(50),
    note          TEXT,

    CONSTRAINT pk_booths PRIMARY KEY (booth_id),
    CONSTRAINT fk_booths_location
        FOREIGN KEY (booth_id)
        REFERENCES locations (location_id)
        ON DELETE RESTRICT
);


CREATE TABLE event_booth_configs
(
    event_booth_config_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id              BIGINT         NOT NULL,
    booth_id              BIGINT         NOT NULL,
    rental_price          NUMERIC(14, 2) NOT NULL,
    is_enabled            BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_event_booth_configs PRIMARY KEY (event_booth_config_id),
    CONSTRAINT fk_event_booth_configs_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_event_booth_configs_booth
        FOREIGN KEY (booth_id)
        REFERENCES booths (booth_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_event_booth_configs_event_booth
        UNIQUE (event_id, booth_id),
    CONSTRAINT ck_event_booth_configs_rental_price_non_negative
        CHECK (rental_price >= 0)
);


CREATE TABLE booth_requests
(
    booth_request_id  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id    BIGINT      NOT NULL,
    booth_id          BIGINT      NOT NULL,
    status            VARCHAR(30) NOT NULL,
    request_note      TEXT,
    review_note       TEXT,
    submitted_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_at       TIMESTAMPTZ,
    selected_at       TIMESTAMPTZ,
    completed_at      TIMESTAMPTZ,
    payment_expired_at TIMESTAMPTZ,
    withdrawn_at      TIMESTAMPTZ,

    CONSTRAINT pk_booth_requests PRIMARY KEY (booth_request_id),
    CONSTRAINT fk_booth_requests_application
        FOREIGN KEY (application_id)
        REFERENCES partner_event_applications (application_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_booth_requests_booth
        FOREIGN KEY (booth_id)
        REFERENCES booths (booth_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_booth_requests_status
        CHECK (status IN (
            'PENDING',
            'SELECTED',
            'COMPLETED',
            'PAYMENT_EXPIRED',
            'NOT_SELECTED',
            'REJECTED',
            'WITHDRAWN'
        ))
);


CREATE TABLE booth_holds
(
    booth_hold_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_booth_config_id BIGINT         NOT NULL,
    booth_request_id     BIGINT         NOT NULL,
    locked_rental_price  NUMERIC(14, 2) NOT NULL,
    status               VARCHAR(20)    NOT NULL,
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at           TIMESTAMPTZ    NOT NULL,
    consumed_at          TIMESTAMPTZ,
    released_at          TIMESTAMPTZ,

    CONSTRAINT pk_booth_holds PRIMARY KEY (booth_hold_id),
    CONSTRAINT fk_booth_holds_event_booth_config
        FOREIGN KEY (event_booth_config_id)
        REFERENCES event_booth_configs (event_booth_config_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_booth_holds_booth_request
        FOREIGN KEY (booth_request_id)
        REFERENCES booth_requests (booth_request_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_booth_holds_booth_request UNIQUE (booth_request_id),
    CONSTRAINT ck_booth_holds_locked_rental_price_non_negative
        CHECK (locked_rental_price >= 0),
    CONSTRAINT ck_booth_holds_status
        CHECK (status IN (
            'ACTIVE',
            'CONSUMED',
            'EXPIRED',
            'RELEASED'
        )),
    CONSTRAINT ck_booth_holds_expiry_after_creation
        CHECK (expires_at > created_at)
);


CREATE INDEX idx_event_booth_configs_event_id
    ON event_booth_configs (event_id);

CREATE INDEX idx_event_booth_configs_booth_id
    ON event_booth_configs (booth_id);

CREATE INDEX idx_booth_requests_application_id
    ON booth_requests (application_id);

CREATE INDEX idx_booth_requests_booth_status
    ON booth_requests (booth_id, status);

CREATE UNIQUE INDEX uk_booth_requests_open_application_booth
    ON booth_requests (application_id, booth_id)
    WHERE status IN ('PENDING', 'SELECTED');

CREATE INDEX idx_booth_holds_event_booth_config_status
    ON booth_holds (event_booth_config_id, status);

CREATE INDEX idx_booth_holds_status_expires_at
    ON booth_holds (status, expires_at);

CREATE UNIQUE INDEX uk_booth_holds_active_event_booth_config
    ON booth_holds (event_booth_config_id)
    WHERE status = 'ACTIVE';
