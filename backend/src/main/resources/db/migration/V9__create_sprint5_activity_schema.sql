CREATE EXTENSION IF NOT EXISTS btree_gist;


DO $$
BEGIN
    IF EXISTS (
        SELECT normalized_code
        FROM (
            SELECT CASE
                WHEN UPPER(BTRIM(code)) ~ '^[A-Z0-9_-]{1,30}$'
                    THEN UPPER(BTRIM(code))
                ELSE 'LEGACY-' || location_id
            END AS normalized_code
            FROM locations
        ) projected_location_codes
        GROUP BY normalized_code
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION
            'Cannot normalize Location codes because projected codes are not unique.';
    END IF;
END
$$;

ALTER TABLE locations
    DROP CONSTRAINT uk_locations_code;

UPDATE locations
SET code = CASE
    WHEN UPPER(BTRIM(code)) ~ '^[A-Z0-9_-]{1,30}$'
        THEN UPPER(BTRIM(code))
    ELSE 'LEGACY-' || location_id
END;

ALTER TABLE locations
    ADD CONSTRAINT ck_locations_code_format
        CHECK (code ~ '^[A-Z0-9_-]{1,30}$'),
    ADD CONSTRAINT ck_locations_type
        CHECK (location_type IN ('BOOTH', 'STAGE', 'WORKSHOP', 'AREA')),
    ADD CONSTRAINT ck_locations_map_x_range
        CHECK (map_x IS NULL OR map_x BETWEEN 0 AND 100),
    ADD CONSTRAINT ck_locations_map_y_range
        CHECK (map_y IS NULL OR map_y BETWEEN 0 AND 100);

CREATE UNIQUE INDEX uk_locations_code_normalized
    ON locations (UPPER(BTRIM(code)));


CREATE TABLE activity_proposals
(
    activity_proposal_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    application_id       BIGINT       NOT NULL,
    location_id          BIGINT       NOT NULL,
    title                VARCHAR(200) NOT NULL,
    description          TEXT,
    activity_type        VARCHAR(50)  NOT NULL,
    proposed_start_at    TIMESTAMPTZ  NOT NULL,
    proposed_end_at      TIMESTAMPTZ  NOT NULL,
    capacity             INTEGER      NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    review_note          TEXT,
    submitted_at         TIMESTAMPTZ  NOT NULL,
    updated_at           TIMESTAMPTZ  NOT NULL,
    reviewed_at          TIMESTAMPTZ,
    withdrawn_at         TIMESTAMPTZ,
    cancelled_at         TIMESTAMPTZ,

    CONSTRAINT pk_activity_proposals PRIMARY KEY (activity_proposal_id),
    CONSTRAINT fk_activity_proposals_application
        FOREIGN KEY (application_id)
        REFERENCES partner_event_applications (application_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_proposals_location
        FOREIGN KEY (location_id)
        REFERENCES locations (location_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_activity_proposals_title_not_blank
        CHECK (BTRIM(title) <> ''),
    CONSTRAINT ck_activity_proposals_type_not_blank
        CHECK (BTRIM(activity_type) <> ''),
    CONSTRAINT ck_activity_proposals_time_range
        CHECK (proposed_end_at > proposed_start_at),
    CONSTRAINT ck_activity_proposals_capacity_positive
        CHECK (capacity > 0),
    CONSTRAINT ck_activity_proposals_status
        CHECK (status IN (
            'PENDING',
            'NEED_CHANGES',
            'APPROVED',
            'REJECTED',
            'WITHDRAWN',
            'CANCELLED'
        )),
    CONSTRAINT ck_activity_proposals_review_metadata
        CHECK (
            status NOT IN ('NEED_CHANGES', 'APPROVED', 'REJECTED')
            OR reviewed_at IS NOT NULL
        ),
    CONSTRAINT ck_activity_proposals_review_note
        CHECK (
            status NOT IN ('NEED_CHANGES', 'REJECTED')
            OR (
                review_note IS NOT NULL
                AND CHAR_LENGTH(BTRIM(review_note)) BETWEEN 10 AND 1000
            )
        ),
    CONSTRAINT ck_activity_proposals_withdrawal_consistency
        CHECK (
            (status = 'WITHDRAWN' AND withdrawn_at IS NOT NULL)
            OR (status <> 'WITHDRAWN' AND withdrawn_at IS NULL)
        ),
    CONSTRAINT ck_activity_proposals_cancellation_consistency
        CHECK (
            (status = 'CANCELLED' AND cancelled_at IS NOT NULL)
            OR (status <> 'CANCELLED' AND cancelled_at IS NULL)
        )
);

CREATE INDEX idx_activity_proposals_application_submitted
    ON activity_proposals (application_id, submitted_at DESC);

CREATE INDEX idx_activity_proposals_status_submitted
    ON activity_proposals (status, submitted_at);

CREATE INDEX idx_activity_proposals_location_id
    ON activity_proposals (location_id);


CREATE TABLE activities
(
    activity_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_id                BIGINT       NOT NULL,
    location_id             BIGINT       NOT NULL,
    source_proposal_id      BIGINT,
    title                   VARCHAR(200) NOT NULL,
    description             TEXT,
    activity_type           VARCHAR(50)  NOT NULL,
    start_at                TIMESTAMPTZ  NOT NULL,
    end_at                  TIMESTAMPTZ  NOT NULL,
    registration_required   BOOLEAN      NOT NULL DEFAULT FALSE,
    registration_deadline_at TIMESTAMPTZ,
    capacity                INTEGER      NOT NULL,
    image_url               TEXT,
    attendance_qr_token     UUID,
    is_certificate_enabled  BOOLEAN      NOT NULL DEFAULT FALSE,
    status                  VARCHAR(20)  NOT NULL,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,
    published_at            TIMESTAMPTZ,
    completed_at            TIMESTAMPTZ,
    cancelled_at            TIMESTAMPTZ,
    cancellation_reason     TEXT,
    cancellation_source     VARCHAR(30),

    CONSTRAINT pk_activities PRIMARY KEY (activity_id),
    CONSTRAINT fk_activities_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activities_location
        FOREIGN KEY (location_id)
        REFERENCES locations (location_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activities_source_proposal
        FOREIGN KEY (source_proposal_id)
        REFERENCES activity_proposals (activity_proposal_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_activities_source_proposal UNIQUE (source_proposal_id),
    CONSTRAINT uk_activities_attendance_qr_token UNIQUE (attendance_qr_token),
    CONSTRAINT ck_activities_title_not_blank
        CHECK (BTRIM(title) <> ''),
    CONSTRAINT ck_activities_type_not_blank
        CHECK (BTRIM(activity_type) <> ''),
    CONSTRAINT ck_activities_time_range
        CHECK (end_at > start_at),
    CONSTRAINT ck_activities_capacity_positive
        CHECK (capacity > 0),
    CONSTRAINT ck_activities_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'ONGOING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_activities_registration_consistency
        CHECK (
            (
                registration_required = FALSE
                AND registration_deadline_at IS NULL
                AND attendance_qr_token IS NULL
                AND is_certificate_enabled = FALSE
            )
            OR (
                registration_required = TRUE
                AND (
                    (published_at IS NULL AND attendance_qr_token IS NULL)
                    OR (
                        published_at IS NOT NULL
                        AND registration_deadline_at IS NOT NULL
                        AND attendance_qr_token IS NOT NULL
                        AND registration_deadline_at <= start_at
                    )
                )
            )
        ),
    CONSTRAINT ck_activities_publication_consistency
        CHECK (
            (status = 'DRAFT' AND published_at IS NULL)
            OR (status IN ('PUBLISHED', 'ONGOING', 'COMPLETED') AND published_at IS NOT NULL)
            OR status = 'CANCELLED'
        ),
    CONSTRAINT ck_activities_completion_consistency
        CHECK (
            (status = 'COMPLETED' AND completed_at IS NOT NULL)
            OR (status <> 'COMPLETED' AND completed_at IS NULL)
        ),
    CONSTRAINT ck_activities_cancellation_consistency
        CHECK (
            (
                status = 'CANCELLED'
                AND cancelled_at IS NOT NULL
                AND cancellation_reason IS NOT NULL
                AND cancellation_source IS NOT NULL
            )
            OR (
                status <> 'CANCELLED'
                AND cancelled_at IS NULL
                AND cancellation_reason IS NULL
                AND cancellation_source IS NULL
            )
        ),
    CONSTRAINT ck_activities_cancellation_reason_length
        CHECK (
            cancellation_reason IS NULL
            OR CHAR_LENGTH(BTRIM(cancellation_reason)) BETWEEN 10 AND 500
        ),
    CONSTRAINT ck_activities_cancellation_source
        CHECK (
            cancellation_source IS NULL
            OR cancellation_source IN (
                'ORGANIZER',
                'PARTNER_REQUEST',
                'EVENT_CANCELLATION',
                'SYSTEM'
            )
        ),
    CONSTRAINT ex_activities_location_time
        EXCLUDE USING gist (
            location_id WITH =,
            tstzrange(start_at, end_at, '[)') WITH &&
        )
        WHERE (status <> 'CANCELLED')
);

CREATE INDEX idx_activities_event_status
    ON activities (event_id, status);

CREATE INDEX idx_activities_location_id
    ON activities (location_id);

CREATE INDEX idx_activities_status_time
    ON activities (status, start_at, end_at);


CREATE TABLE activity_requests
(
    activity_request_id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_id                     BIGINT       NOT NULL,
    request_type                    VARCHAR(20)  NOT NULL,
    requested_location_id           BIGINT,
    requested_title                 VARCHAR(200),
    requested_description           TEXT,
    requested_description_present   BOOLEAN      NOT NULL DEFAULT FALSE,
    requested_activity_type         VARCHAR(50),
    requested_start_at              TIMESTAMPTZ,
    requested_end_at                TIMESTAMPTZ,
    requested_capacity              INTEGER,
    requested_image_url             TEXT,
    requested_image_url_present     BOOLEAN      NOT NULL DEFAULT FALSE,
    reason                          TEXT         NOT NULL,
    is_late                         BOOLEAN      NOT NULL DEFAULT FALSE,
    status                          VARCHAR(20)  NOT NULL,
    review_note                     TEXT,
    submitted_at                    TIMESTAMPTZ  NOT NULL,
    handled_at                      TIMESTAMPTZ,
    withdrawn_at                    TIMESTAMPTZ,
    cancelled_at                    TIMESTAMPTZ,

    CONSTRAINT pk_activity_requests PRIMARY KEY (activity_request_id),
    CONSTRAINT fk_activity_requests_activity
        FOREIGN KEY (activity_id)
        REFERENCES activities (activity_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_requests_requested_location
        FOREIGN KEY (requested_location_id)
        REFERENCES locations (location_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_activity_requests_type
        CHECK (request_type IN ('CHANGE', 'CANCELLATION')),
    CONSTRAINT ck_activity_requests_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN', 'CANCELLED')),
    CONSTRAINT ck_activity_requests_reason_length
        CHECK (CHAR_LENGTH(BTRIM(reason)) BETWEEN 10 AND 500),
    CONSTRAINT ck_activity_requests_requested_title
        CHECK (requested_title IS NULL OR BTRIM(requested_title) <> ''),
    CONSTRAINT ck_activity_requests_requested_type
        CHECK (requested_activity_type IS NULL OR BTRIM(requested_activity_type) <> ''),
    CONSTRAINT ck_activity_requests_requested_time_pair
        CHECK (
            (requested_start_at IS NULL AND requested_end_at IS NULL)
            OR (
                requested_start_at IS NOT NULL
                AND requested_end_at IS NOT NULL
                AND requested_end_at > requested_start_at
            )
        ),
    CONSTRAINT ck_activity_requests_requested_capacity
        CHECK (requested_capacity IS NULL OR requested_capacity > 0),
    CONSTRAINT ck_activity_requests_payload_by_type
        CHECK (
            (
                request_type = 'CHANGE'
                AND is_late = FALSE
                AND (
                    requested_location_id IS NOT NULL
                    OR requested_title IS NOT NULL
                    OR requested_description_present = TRUE
                    OR requested_activity_type IS NOT NULL
                    OR requested_start_at IS NOT NULL
                    OR requested_capacity IS NOT NULL
                    OR requested_image_url_present = TRUE
                )
            )
            OR (
                request_type = 'CANCELLATION'
                AND requested_location_id IS NULL
                AND requested_title IS NULL
                AND requested_description IS NULL
                AND requested_description_present = FALSE
                AND requested_activity_type IS NULL
                AND requested_start_at IS NULL
                AND requested_end_at IS NULL
                AND requested_capacity IS NULL
                AND requested_image_url IS NULL
                AND requested_image_url_present = FALSE
            )
        ),
    CONSTRAINT ck_activity_requests_description_presence
        CHECK (requested_description_present OR requested_description IS NULL),
    CONSTRAINT ck_activity_requests_image_presence
        CHECK (requested_image_url_present OR requested_image_url IS NULL),
    CONSTRAINT ck_activity_requests_terminal_timestamps
        CHECK (
            (
                status = 'PENDING'
                AND handled_at IS NULL
                AND withdrawn_at IS NULL
                AND cancelled_at IS NULL
            )
            OR (
                status IN ('APPROVED', 'REJECTED')
                AND handled_at IS NOT NULL
                AND withdrawn_at IS NULL
                AND cancelled_at IS NULL
            )
            OR (
                status = 'WITHDRAWN'
                AND handled_at IS NULL
                AND withdrawn_at IS NOT NULL
                AND cancelled_at IS NULL
            )
            OR (
                status = 'CANCELLED'
                AND handled_at IS NULL
                AND withdrawn_at IS NULL
                AND cancelled_at IS NOT NULL
            )
        ),
    CONSTRAINT ck_activity_requests_rejection_note
        CHECK (
            status <> 'REJECTED'
            OR (
                review_note IS NOT NULL
                AND CHAR_LENGTH(BTRIM(review_note)) BETWEEN 10 AND 1000
            )
        )
);

CREATE INDEX idx_activity_requests_activity_status
    ON activity_requests (activity_id, status);

CREATE INDEX idx_activity_requests_status_submitted
    ON activity_requests (status, submitted_at);

CREATE INDEX idx_activity_requests_requested_location
    ON activity_requests (requested_location_id)
    WHERE requested_location_id IS NOT NULL;

CREATE UNIQUE INDEX uk_activity_requests_one_pending
    ON activity_requests (activity_id)
    WHERE status = 'PENDING';


CREATE TABLE activity_revisions
(
    activity_revision_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    activity_id          BIGINT      NOT NULL,
    actor_user_id        BIGINT,
    source_request_id    BIGINT,
    revision_source      VARCHAR(30) NOT NULL,
    change_reason        TEXT,
    old_snapshot         JSONB       NOT NULL,
    new_snapshot         JSONB       NOT NULL,
    changed_at           TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_activity_revisions PRIMARY KEY (activity_revision_id),
    CONSTRAINT fk_activity_revisions_activity
        FOREIGN KEY (activity_id)
        REFERENCES activities (activity_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_revisions_actor_user
        FOREIGN KEY (actor_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_activity_revisions_source_request
        FOREIGN KEY (source_request_id)
        REFERENCES activity_requests (activity_request_id)
        ON DELETE RESTRICT,
    CONSTRAINT ck_activity_revisions_source
        CHECK (revision_source IN (
            'ORGANIZER_DIRECT',
            'PARTNER_REQUEST',
            'EVENT_CANCELLATION',
            'SYSTEM'
        )),
    CONSTRAINT ck_activity_revisions_change_reason_length
        CHECK (
            change_reason IS NULL
            OR CHAR_LENGTH(BTRIM(change_reason)) BETWEEN 10 AND 500
        ),
    CONSTRAINT ck_activity_revisions_old_snapshot_object
        CHECK (jsonb_typeof(old_snapshot) = 'object'),
    CONSTRAINT ck_activity_revisions_new_snapshot_object
        CHECK (jsonb_typeof(new_snapshot) = 'object')
);

CREATE INDEX idx_activity_revisions_activity_changed
    ON activity_revisions (activity_id, changed_at, activity_revision_id);

CREATE INDEX idx_activity_revisions_source_request
    ON activity_revisions (source_request_id)
    WHERE source_request_id IS NOT NULL;
