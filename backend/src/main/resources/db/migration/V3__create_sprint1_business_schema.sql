CREATE TABLE events
(
    event_id                             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    organizer_user_id                    BIGINT       NOT NULL,
    name                                 VARCHAR(150) NOT NULL,
    description                          TEXT,
    start_at                             TIMESTAMPTZ  NOT NULL,
    end_at                               TIMESTAMPTZ  NOT NULL,
    partner_application_deadline_at      TIMESTAMPTZ,
    booth_request_deadline_at            TIMESTAMPTZ,
    activity_proposal_deadline_at        TIMESTAMPTZ,
    participant_registration_deadline_at TIMESTAMPTZ,
    partner_withdrawal_cutoff_at         TIMESTAMPTZ,
    booth_cancellation_cutoff_at         TIMESTAMPTZ,
    activity_cancellation_cutoff_at      TIMESTAMPTZ,
    booth_payment_window_minutes         INTEGER      NOT NULL,
    max_booths_per_partner               INTEGER      NOT NULL,
    max_activities_per_partner           INTEGER      NOT NULL,
    banner_url                           TEXT,
    status                               VARCHAR(20)  NOT NULL,
    created_at                           TIMESTAMPTZ  NOT NULL,
    updated_at                           TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_events PRIMARY KEY (event_id),

    CONSTRAINT fk_events_organizer_user
        FOREIGN KEY (organizer_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_events_time_range
        CHECK (end_at > start_at),

    CONSTRAINT ck_events_booth_payment_window_non_negative
        CHECK (booth_payment_window_minutes >= 0),

    CONSTRAINT ck_events_max_booths_per_partner_non_negative
        CHECK (max_booths_per_partner >= 0),

    CONSTRAINT ck_events_max_activities_per_partner_non_negative
        CHECK (max_activities_per_partner >= 0),

    CONSTRAINT ck_events_status
        CHECK (status IN (
            'DRAFT',
            'PUBLISHED',
            'ONGOING',
            'COMPLETED',
            'CANCELLED'
        ))
);


CREATE TABLE partner_organizations
(
    partner_organization_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    representative_user_id  BIGINT       NOT NULL,
    name                    VARCHAR(150) NOT NULL,
    description             TEXT,
    category_code           VARCHAR(50)  NOT NULL,
    logo_url                TEXT,
    contact_email           VARCHAR(255),
    contact_phone           VARCHAR(20),
    address                 TEXT,
    status                  VARCHAR(20)  NOT NULL,
    created_at              TIMESTAMPTZ  NOT NULL,
    updated_at              TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_partner_organizations
        PRIMARY KEY (partner_organization_id),

    CONSTRAINT fk_partner_organizations_representative_user
        FOREIGN KEY (representative_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_partner_organizations_representative_user
        UNIQUE (representative_user_id),

    CONSTRAINT ck_partner_organizations_status
        CHECK (status IN (
            'ACTIVE',
            'INACTIVE'
        ))
);


CREATE TABLE partner_event_applications
(
    application_id          BIGINT GENERATED BY DEFAULT AS IDENTITY,
    partner_organization_id BIGINT      NOT NULL,
    event_id                BIGINT      NOT NULL,
    status                  VARCHAR(20) NOT NULL,
    application_note        TEXT,
    review_note             TEXT,
    submitted_at            TIMESTAMPTZ NOT NULL,
    reviewed_at             TIMESTAMPTZ,
    withdrawn_at            TIMESTAMPTZ,

    CONSTRAINT pk_partner_event_applications
        PRIMARY KEY (application_id),

    CONSTRAINT fk_partner_event_applications_partner_organization
        FOREIGN KEY (partner_organization_id)
        REFERENCES partner_organizations (partner_organization_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_partner_event_applications_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_partner_event_applications_partner_event
        UNIQUE (partner_organization_id, event_id),

    CONSTRAINT ck_partner_event_applications_status
        CHECK (status IN (
            'PENDING',
            'APPROVED',
            'REJECTED',
            'WITHDRAWN'
        ))
);


CREATE INDEX idx_events_organizer_user_id
    ON events (organizer_user_id);

CREATE INDEX idx_partner_event_applications_event_id
    ON partner_event_applications (event_id);
