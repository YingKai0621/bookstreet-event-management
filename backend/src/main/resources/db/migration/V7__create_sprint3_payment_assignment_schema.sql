CREATE TABLE booth_payments
(
    booth_payment_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booth_hold_id                    BIGINT         NOT NULL,
    original_payment_id              BIGINT,
    transaction_type                 VARCHAR(20)    NOT NULL,
    purpose                          VARCHAR(40)    NOT NULL,
    amount                           NUMERIC(14, 2) NOT NULL,
    status                           VARCHAR(20)    NOT NULL,
    idempotency_key                  UUID           NOT NULL,
    gateway_provider                 VARCHAR(30)    NOT NULL,
    gateway_transaction_ref          VARCHAR(150),
    checkout_url                     TEXT,
    checkout_expires_at              TIMESTAMPTZ,
    provider_response_code           VARCHAR(10),
    provider_transaction_status      VARCHAR(10),
    last_gateway_query_at            TIMESTAMPTZ,
    trusted_incomplete_query_count   SMALLINT       NOT NULL DEFAULT 0,
    reconciliation_required          BOOLEAN        NOT NULL DEFAULT FALSE,
    reconciliation_detail            TEXT,
    failure_code                     VARCHAR(50),
    failure_message                  TEXT,
    created_at                       TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                       TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at                     TIMESTAMPTZ,

    CONSTRAINT pk_booth_payments PRIMARY KEY (booth_payment_id),
    CONSTRAINT fk_booth_payments_hold
        FOREIGN KEY (booth_hold_id)
        REFERENCES booth_holds (booth_hold_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_booth_payments_original
        FOREIGN KEY (original_payment_id)
        REFERENCES booth_payments (booth_payment_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_booth_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_booth_payments_transaction_type
        CHECK (transaction_type IN ('PAYMENT', 'REFUND')),
    CONSTRAINT ck_booth_payments_purpose_not_blank
        CHECK (BTRIM(purpose) <> ''),
    CONSTRAINT ck_booth_payments_amount_non_negative
        CHECK (amount >= 0),
    CONSTRAINT ck_booth_payments_status
        CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'TIMEOUT')),
    CONSTRAINT ck_booth_payments_gateway_provider_not_blank
        CHECK (BTRIM(gateway_provider) <> ''),
    CONSTRAINT ck_booth_payments_query_count
        CHECK (trusted_incomplete_query_count BETWEEN 0 AND 2),
    CONSTRAINT ck_booth_payments_completion
        CHECK ((status = 'PENDING' AND completed_at IS NULL)
            OR (status <> 'PENDING' AND completed_at IS NOT NULL)),
    CONSTRAINT ck_booth_payments_original_reference
        CHECK ((transaction_type = 'PAYMENT' AND original_payment_id IS NULL)
            OR transaction_type = 'REFUND')
);

CREATE UNIQUE INDEX uk_booth_payments_gateway_reference
    ON booth_payments (gateway_provider, gateway_transaction_ref)
    WHERE gateway_transaction_ref IS NOT NULL;

CREATE UNIQUE INDEX uk_booth_payments_pending_initial_rental_hold
    ON booth_payments (booth_hold_id)
    WHERE transaction_type = 'PAYMENT'
      AND purpose = 'INITIAL_BOOTH_RENTAL'
      AND status = 'PENDING';

CREATE UNIQUE INDEX uk_booth_payments_success_initial_rental_hold
    ON booth_payments (booth_hold_id)
    WHERE transaction_type = 'PAYMENT'
      AND purpose = 'INITIAL_BOOTH_RENTAL'
      AND status = 'SUCCESS';

CREATE INDEX idx_booth_payments_hold_status
    ON booth_payments (booth_hold_id, status);

CREATE INDEX idx_booth_payments_reconciliation
    ON booth_payments (status, reconciliation_required, checkout_expires_at,
        last_gateway_query_at)
    WHERE status = 'PENDING';


CREATE TABLE booth_assignments
(
    booth_assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booth_hold_id       BIGINT       NOT NULL,
    qr_token            UUID         NOT NULL,
    cover_image_url     TEXT,
    status              VARCHAR(20)  NOT NULL,
    assigned_at         TIMESTAMPTZ  NOT NULL,
    released_at         TIMESTAMPTZ,
    release_reason      VARCHAR(30),

    CONSTRAINT pk_booth_assignments PRIMARY KEY (booth_assignment_id),
    CONSTRAINT fk_booth_assignments_hold
        FOREIGN KEY (booth_hold_id)
        REFERENCES booth_holds (booth_hold_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_booth_assignments_hold UNIQUE (booth_hold_id),
    CONSTRAINT uk_booth_assignments_qr_token UNIQUE (qr_token),
    CONSTRAINT ck_booth_assignments_status
        CHECK (status IN ('ACTIVE', 'RELEASED', 'CANCELLED', 'ENDED')),
    CONSTRAINT ck_booth_assignments_release
        CHECK ((status = 'ACTIVE' AND released_at IS NULL)
            OR status <> 'ACTIVE')
);

CREATE INDEX idx_booth_assignments_status
    ON booth_assignments (status);
