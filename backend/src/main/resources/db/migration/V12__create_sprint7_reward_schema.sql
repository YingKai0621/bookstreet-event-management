CREATE TABLE booth_visits
(
    booth_visit_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    event_registration_id BIGINT      NOT NULL,
    booth_assignment_id   BIGINT      NOT NULL,
    visited_at            TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_booth_visits PRIMARY KEY (booth_visit_id),
    CONSTRAINT fk_booth_visits_event_registration
        FOREIGN KEY (event_registration_id)
        REFERENCES event_registrations (event_registration_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_booth_visits_booth_assignment
        FOREIGN KEY (booth_assignment_id)
        REFERENCES booth_assignments (booth_assignment_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_booth_visits_registration_assignment
        UNIQUE (event_registration_id, booth_assignment_id)
);

CREATE INDEX idx_booth_visits_registration_visited
    ON booth_visits (event_registration_id, visited_at DESC, booth_visit_id DESC);

CREATE INDEX idx_booth_visits_assignment_visited
    ON booth_visits (booth_assignment_id, visited_at DESC, booth_visit_id DESC);


CREATE TABLE point_transactions
(
    point_transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booth_visit_id       BIGINT      NOT NULL,
    points               INTEGER     NOT NULL,
    created_at           TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_point_transactions PRIMARY KEY (point_transaction_id),
    CONSTRAINT fk_point_transactions_booth_visit
        FOREIGN KEY (booth_visit_id)
        REFERENCES booth_visits (booth_visit_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_point_transactions_booth_visit UNIQUE (booth_visit_id),
    CONSTRAINT ck_point_transactions_points CHECK (points > 0)
);

CREATE INDEX idx_point_transactions_created
    ON point_transactions (created_at DESC, point_transaction_id DESC);


CREATE TABLE badges
(
    badge_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name            VARCHAR(100) NOT NULL,
    description     TEXT,
    required_points INTEGER      NOT NULL,
    icon_url        TEXT,
    is_active       BOOLEAN      NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL,

    CONSTRAINT pk_badges PRIMARY KEY (badge_id),
    CONSTRAINT ck_badges_name
        CHECK (
            name = REGEXP_REPLACE(BTRIM(name), '[[:space:]]+', ' ', 'g')
            AND CHAR_LENGTH(name) BETWEEN 1 AND 100
        ),
    CONSTRAINT ck_badges_description
        CHECK (
            description IS NULL
            OR (
                description = BTRIM(description)
                AND CHAR_LENGTH(description) BETWEEN 1 AND 1000
            )
        ),
    CONSTRAINT ck_badges_required_points CHECK (required_points > 0),
    CONSTRAINT ck_badges_icon_url
        CHECK (
            icon_url IS NULL
            OR (
                icon_url = BTRIM(icon_url)
                AND CHAR_LENGTH(icon_url) BETWEEN 1 AND 2048
            )
        ),
    CONSTRAINT ck_badges_timestamps CHECK (updated_at >= created_at)
);

CREATE UNIQUE INDEX uk_badges_name_case_insensitive
    ON badges (LOWER(name));

CREATE INDEX idx_badges_active_required
    ON badges (is_active, required_points, badge_id);


CREATE TABLE user_badges
(
    user_badge_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id       BIGINT      NOT NULL,
    badge_id      BIGINT      NOT NULL,
    earned_at     TIMESTAMPTZ NOT NULL,

    CONSTRAINT pk_user_badges PRIMARY KEY (user_badge_id),
    CONSTRAINT fk_user_badges_user
        FOREIGN KEY (user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_user_badges_badge
        FOREIGN KEY (badge_id)
        REFERENCES badges (badge_id)
        ON DELETE RESTRICT,
    CONSTRAINT uk_user_badges_user_badge UNIQUE (user_id, badge_id)
);

CREATE INDEX idx_user_badges_user_earned
    ON user_badges (user_id, earned_at DESC, user_badge_id DESC);

CREATE INDEX idx_user_badges_badge_user
    ON user_badges (badge_id, user_id);


