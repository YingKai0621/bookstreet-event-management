ALTER TABLE notifications
    ADD CONSTRAINT ck_notifications_type
        CHECK (notification_type IN (
            'ACTIVITY_SCHEDULE_OR_LOCATION_CHANGED',
            'ACTIVITY_CANCELLED',
            'EVENT_CANCELLED',
            'CERTIFICATE_ISSUED',
            'CERTIFICATE_REVOKED',
            'BADGE_UNLOCKED'
        )),
    ADD CONSTRAINT ck_notifications_reference
        CHECK (
            (
                notification_type IN (
                    'ACTIVITY_SCHEDULE_OR_LOCATION_CHANGED',
                    'ACTIVITY_CANCELLED'
                )
                AND activity_id IS NOT NULL
                AND event_id IS NULL
                AND certificate_id IS NULL
                AND badge_id IS NULL
            )
            OR (
                notification_type = 'EVENT_CANCELLED'
                AND event_id IS NOT NULL
                AND activity_id IS NULL
                AND certificate_id IS NULL
                AND badge_id IS NULL
            )
            OR (
                notification_type IN ('CERTIFICATE_ISSUED', 'CERTIFICATE_REVOKED')
                AND certificate_id IS NOT NULL
                AND event_id IS NULL
                AND activity_id IS NULL
                AND badge_id IS NULL
            )
            OR (
                notification_type = 'BADGE_UNLOCKED'
                AND badge_id IS NOT NULL
                AND event_id IS NULL
                AND activity_id IS NULL
                AND certificate_id IS NULL
            )
        );

CREATE INDEX idx_notifications_badge
    ON notifications (badge_id, notification_id);
