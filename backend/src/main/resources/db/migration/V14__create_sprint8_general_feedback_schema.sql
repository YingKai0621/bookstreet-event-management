CREATE TABLE general_feedbacks
(
    general_feedback_id       BIGINT GENERATED BY DEFAULT AS IDENTITY,
    submitted_by_user_id      BIGINT,
    target_type               VARCHAR(20)   NOT NULL,
    event_id                  BIGINT,
    guest_name                VARCHAR(100),
    contact_email             VARCHAR(255),
    message                   TEXT          NOT NULL,
    status                    VARCHAR(20)   NOT NULL DEFAULT 'NEW',
    internal_note             VARCHAR(1000),
    last_handled_by_user_id   BIGINT,
    handling_started_at       TIMESTAMPTZ,
    submitted_at              TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at               TIMESTAMPTZ,

    CONSTRAINT pk_general_feedbacks PRIMARY KEY (general_feedback_id),

    CONSTRAINT fk_general_feedbacks_submitted_by_user
        FOREIGN KEY (submitted_by_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_general_feedbacks_event
        FOREIGN KEY (event_id)
        REFERENCES events (event_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_general_feedbacks_last_handled_by_user
        FOREIGN KEY (last_handled_by_user_id)
        REFERENCES users (user_id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_general_feedbacks_target_type
        CHECK (target_type IN ('BOOK_STREET', 'EVENT')),

    CONSTRAINT ck_general_feedbacks_target_reference
        CHECK (
            (target_type = 'BOOK_STREET' AND event_id IS NULL)
            OR
            (target_type = 'EVENT' AND event_id IS NOT NULL)
        ),

    CONSTRAINT ck_general_feedbacks_status
        CHECK (status IN ('NEW', 'IN_PROGRESS', 'RESOLVED')),

    CONSTRAINT ck_general_feedbacks_guest_name
        CHECK (
            guest_name IS NULL
            OR (
                guest_name = BTRIM(guest_name)
                AND guest_name = REGEXP_REPLACE(guest_name, '[[:space:]]+', ' ', 'g')
                AND CHAR_LENGTH(guest_name) BETWEEN 1 AND 100
            )
        ),

    CONSTRAINT ck_general_feedbacks_contact_email
        CHECK (
            contact_email IS NULL
            OR (
                contact_email = REGEXP_REPLACE(contact_email, '^[[:space:]]+|[[:space:]]+$', '', 'g')
                AND contact_email = LOWER(contact_email)
                AND CHAR_LENGTH(contact_email) BETWEEN 3 AND 255
            )
        ),

    CONSTRAINT ck_general_feedbacks_message
        CHECK (
            message = REGEXP_REPLACE(message, '^[[:space:]]+|[[:space:]]+$', '', 'g')
            AND CHAR_LENGTH(message) BETWEEN 10 AND 2000
        ),

    CONSTRAINT ck_general_feedbacks_internal_note
        CHECK (
            internal_note IS NULL
            OR (
                internal_note = BTRIM(internal_note)
                AND internal_note = REGEXP_REPLACE(internal_note, '[[:space:]]+', ' ', 'g')
                AND CHAR_LENGTH(internal_note) BETWEEN 1 AND 1000
            )
        ),

    CONSTRAINT ck_general_feedbacks_workflow_state
        CHECK (
            (
                status = 'NEW'
                AND last_handled_by_user_id IS NULL
                AND handling_started_at IS NULL
                AND resolved_at IS NULL
                AND internal_note IS NULL
            )
            OR
            (
                status = 'IN_PROGRESS'
                AND last_handled_by_user_id IS NOT NULL
                AND handling_started_at IS NOT NULL
                AND resolved_at IS NULL
            )
            OR
            (
                status = 'RESOLVED'
                AND last_handled_by_user_id IS NOT NULL
                AND handling_started_at IS NOT NULL
                AND resolved_at IS NOT NULL
                AND internal_note IS NOT NULL
            )
        ),

    CONSTRAINT ck_general_feedbacks_timestamps
        CHECK (
            submitted_at <= updated_at
            AND (
                handling_started_at IS NULL
                OR (handling_started_at >= submitted_at AND handling_started_at <= updated_at)
            )
            AND (
                resolved_at IS NULL
                OR (
                    handling_started_at IS NOT NULL
                    AND resolved_at >= handling_started_at
                    AND resolved_at <= updated_at
                )
            )
        )
);

CREATE INDEX idx_general_feedbacks_queue
    ON general_feedbacks (submitted_at DESC, general_feedback_id DESC);

CREATE INDEX idx_general_feedbacks_status_queue
    ON general_feedbacks (status, submitted_at DESC, general_feedback_id DESC);

CREATE INDEX idx_general_feedbacks_event_queue
    ON general_feedbacks (event_id, status, submitted_at DESC, general_feedback_id DESC)
    WHERE event_id IS NOT NULL;
