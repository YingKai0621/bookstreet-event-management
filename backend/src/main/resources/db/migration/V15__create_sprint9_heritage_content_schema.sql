CREATE TABLE heritage_contents
(
    heritage_content_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    public_code         VARCHAR(100) NOT NULL,
    title               VARCHAR(200) NOT NULL,
    summary             TEXT,
    content             TEXT         NOT NULL,
    image_url           TEXT,
    location_text       VARCHAR(255),
    status              VARCHAR(20)  NOT NULL DEFAULT 'DRAFT',
    published_at        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_heritage_contents PRIMARY KEY (heritage_content_id),

    CONSTRAINT uq_heritage_contents_public_code UNIQUE (public_code),

    CONSTRAINT ck_heritage_contents_public_code
        CHECK (
            public_code = BTRIM(public_code)
            AND public_code = UPPER(public_code)
            AND CHAR_LENGTH(public_code) BETWEEN 3 AND 100
            AND public_code ~ '^[A-Z][A-Z0-9]*(-[A-Z0-9]+)*$'
        ),

    CONSTRAINT ck_heritage_contents_title
        CHECK (
            title = BTRIM(title)
            AND CHAR_LENGTH(title) BETWEEN 2 AND 200
        ),

    CONSTRAINT ck_heritage_contents_summary
        CHECK (
            summary IS NULL
            OR (
                summary = BTRIM(summary)
                AND CHAR_LENGTH(summary) BETWEEN 1 AND 1000
            )
        ),

    CONSTRAINT ck_heritage_contents_content
        CHECK (
            content = REGEXP_REPLACE(content, '^[[:space:]]+|[[:space:]]+$', '', 'g')
            AND CHAR_LENGTH(content) BETWEEN 20 AND 20000
        ),

    CONSTRAINT ck_heritage_contents_image_url
        CHECK (
            image_url IS NULL
            OR (
                image_url = BTRIM(image_url)
                AND CHAR_LENGTH(image_url) BETWEEN 1 AND 2048
                AND (
                    LOWER(image_url) LIKE 'http://%'
                    OR LOWER(image_url) LIKE 'https://%'
                    OR image_url LIKE '/assets/heritage/%'
                )
            )
        ),

    CONSTRAINT ck_heritage_contents_location_text
        CHECK (
            location_text IS NULL
            OR (
                location_text = BTRIM(location_text)
                AND CHAR_LENGTH(location_text) BETWEEN 1 AND 255
            )
        ),

    CONSTRAINT ck_heritage_contents_status
        CHECK (status IN ('DRAFT', 'PUBLISHED', 'ARCHIVED')),

    CONSTRAINT ck_heritage_contents_publication_state
        CHECK (
            (status = 'DRAFT' AND published_at IS NULL)
            OR
            (status IN ('PUBLISHED', 'ARCHIVED') AND published_at IS NOT NULL)
        ),

    CONSTRAINT ck_heritage_contents_timestamps
        CHECK (
            created_at <= updated_at
            AND (
                published_at IS NULL
                OR (published_at >= created_at AND published_at <= updated_at)
            )
        )
);

CREATE INDEX idx_heritage_contents_public_published
    ON heritage_contents (published_at DESC, heritage_content_id DESC)
    WHERE status = 'PUBLISHED';

CREATE INDEX idx_heritage_contents_status_updated
    ON heritage_contents (status, updated_at DESC, heritage_content_id DESC);
